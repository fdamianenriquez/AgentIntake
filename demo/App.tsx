import { AgentIntakeForm } from '../packages/react-agent-intake/src/index.js';
import { GeneratedFlowSchema, type FlowDef } from '../packages/react-agent-intake/src/contracts.js';
import rawFlow from './flow.json' with { type: 'json' };

const API_URL = import.meta.env.VITE_API_URL ?? 'http://localhost:3000';

// Validated (not just cast) so a hand-edited flow.json that drifted from the
// schema fails loudly here rather than producing subtly-wrong form controls
// -- also gives properly-typed fields, which a raw JSON import loses (its
// `type` fields infer as plain `string`, not the FieldDef literal union).
const generatedFlow = GeneratedFlowSchema.parse(rawFlow);

// flow.json is generated by the CLI and reviewed by hand --
// it never includes execute(), so real (non-simulated) implementations are
// wired up here. Each one just logs and resolves successfully;
// what makes them "real" rather than simulated is that this is the flow
// author's own deliberate implementation, not infrastructure substituting a
// stand-in (that's what Studio's simulated mode, does instead).
function makeExecute(endpointId: string, endpointTitle: string) {
  return async (data: Record<string, unknown>) => {
    console.log(`Would call the "${endpointTitle}" endpoint (${endpointId}) with:`, data);
    return { success: true, message: `${endpointTitle} recorded.` };
  };
}

const flow: FlowDef = {
  ...generatedFlow,
  endpoints: generatedFlow.endpoints.map((endpoint) => ({
    ...endpoint,
    execute: makeExecute(endpoint.id, endpoint.title),
  })),
};

export function App() {
  return (
    <main className="demo-app">
      <h1>{flow.title}</h1>
      <p>{flow.description}</p>
      <p className="demo-app-note">
        This demo calls a real, locally-running AgentIntake server for adaptive fields and semantic
        validation, but each step's "execute" just logs to the browser console instead of hitting a real
        API. Field names here are deliberately generic and fictional -- this demonstrates the mechanism,
        not real KYC/KYB compliance requirements for any jurisdiction.
      </p>
      <AgentIntakeForm flow={flow} apiUrl={API_URL} />
    </main>
  );
}
